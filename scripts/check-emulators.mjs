import assert from 'node:assert/strict';
import { initializeApp, deleteApp } from 'firebase/app';
import { getAuth, connectAuthEmulator, createUserWithEmailAndPassword, inMemoryPersistence, setPersistence } from 'firebase/auth';
import { getFirestore, connectFirestoreEmulator, doc, getDoc, collection, query, where, getDocs, setDoc } from 'firebase/firestore';
import { getFunctions, connectFunctionsEmulator, httpsCallable } from 'firebase/functions';
import { getStorage, connectStorageEmulator, ref, uploadBytes, getBytes } from 'firebase/storage';
const projectId = 'demo-apoiapet';
const stamp = Date.now();
const accounts = [];
const timeout = setTimeout(() => { console.error('Tempo limite: confira os emuladores.'); process.exit(1); }, 120000);
async function account(label, role) {
  const app = initializeApp({ apiKey: 'demo-key', projectId, authDomain: `${projectId}.firebaseapp.com`, storageBucket: `${projectId}.appspot.com` }, `${label}-${stamp}`);
  accounts.push(app);
  const auth = getAuth(app); connectAuthEmulator(auth, 'http://127.0.0.1:9099', { disableWarnings: true });
  await setPersistence(auth, inMemoryPersistence);
  const db = getFirestore(app); connectFirestoreEmulator(db, '127.0.0.1', 8080);
  const functions = getFunctions(app, 'southamerica-east1'); connectFunctionsEmulator(functions, '127.0.0.1', 5001);
  const storage = getStorage(app); connectStorageEmulator(storage, '127.0.0.1', 9199);
  const { user } = await createUserWithEmailAndPassword(auth, `${label}-${stamp}@example.test`, 'TesteLocal!123');
  const call = async (name, data) => (await httpsCallable(functions, name)(data)).data;
  await call('saveProfile', { role, fullName: `Pessoa ${label}`, ongName: `Abrigo ${label}`, phone: '11987654321', cep: '01001000' });
  return { uid: user.uid, db, call, storage };
}
try {
  const hub = await fetch('http://127.0.0.1:4400/emulators');
  assert.equal(hub.ok, true, 'Inicie npm.cmd run emulators');
  const ong = await account('ongteste', 'ong');
  const donor = await account('adotanteteste', 'donor');
  const outsider = await account('outroteste', 'ong');
  console.log('PASS: cadastro e perfil nos emuladores de Auth/Functions/Firestore.');
  await assert.rejects(getDoc(doc(outsider.db, 'privateProfiles', donor.uid)));
  await assert.rejects(setDoc(doc(donor.db, 'profiles', donor.uid), { role: 'ong' }));
  const png = Uint8Array.from(Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a2ioAAAAASUVORK5CYII=', 'base64'));
  const petPhoto = `pets/${ong.uid}/local-${stamp}.png`;
  await uploadBytes(ref(ong.storage, petPhoto), png, { contentType: 'image/png' });
  const { id: petId } = await ong.call('savePet', { name: `Pet teste ${stamp}`, species: 'Gato', age: '1 ano', description: 'Registro de verificação local', health: { vaccinesDone: ['v3'], vaccinesNeeded: ['rabies'], tests: [{ id: 'fiv', result: 'not_informed' }, { id: 'felv', result: 'negative' }], notes: 'Registro de teste' }, photoPath: petPhoto });
  const savedPet = (await getDoc(doc(ong.db, 'pets', petId))).data();
  assert.deepEqual(savedPet.health.vaccinesDone, ['v3']);
  assert.equal(savedPet.health.tests.find(item => item.id === 'fiv').result, 'not_informed');
  assert.equal(savedPet.health.tests.find(item => item.id === 'felv').result, 'negative');
  const appId = `${petId}_${donor.uid}`;
  const homePhoto = `homes/${donor.uid}/${appId}/local.png`;
  await uploadBytes(ref(donor.storage, homePhoto), png, { contentType: 'image/png' });
  const result = await donor.call('submitApplication', { petId, housing: 'Apartamento', safety: 'Telas nas janelas', routine: 'Cuidados diários', motivation: 'Acolhimento', consent: true, photoPaths: [homePhoto] });
  assert.equal(result.id, appId);
  const inbox = await getDocs(query(collection(ong.db, 'applications'), where('ongId', '==', ong.uid)));
  assert.ok(inbox.docs.some(item => item.id === appId));
  assert.equal((await getBytes(ref(ong.storage, homePhoto))).byteLength, png.byteLength);
  await assert.rejects(getDoc(doc(outsider.db, 'applications', appId)));
  await assert.rejects(getBytes(ref(outsider.storage, homePhoto)));
  console.log('PASS: envio de fotos, candidatura entregue à ONG e isolamento por regras reais.');
  await ong.call('changeApplication', { id: appId, action: 'approve' });
  await donor.call('sendMessage', { id: appId, body: 'Vamos combinar a retirada.' });
  await ong.call('changeApplication', { id: appId, action: 'schedule', pickupAt: new Date(Date.now() + 86400000).toISOString(), pickupPlace: 'Abrigo de teste' });
  assert.equal((await getDoc(doc(donor.db, 'pets', petId))).data().status, 'in_process');
  await ong.call('changeApplication', { id: appId, action: 'complete' });
  assert.equal((await getDoc(doc(ong.db, 'pets', petId))).data().listed, false);
  const history = await getDocs(query(collection(donor.db, 'applications'), where('applicantId', '==', donor.uid)));
  assert.equal(history.docs.find(item => item.id === appId).data().status, 'adopted');
  const donation = await donor.call('createDonation', { ongId: ong.uid, amountCents: 2500, mode: 'test', requestId: `smoke-request-${stamp}` });
  await donor.call('simulateDonation', { id: donation.id, status: 'confirmed' });
  const received = await getDocs(query(collection(ong.db, 'donations'), where('ongId', '==', ong.uid)));
  assert.equal(received.docs.find(item => item.id === donation.id).data().status, 'confirmed');
  await assert.rejects(getDoc(doc(outsider.db, 'donations', donation.id)));
  console.log('PASS: aprovação, chat, agenda, retirada e histórico de adoção/doação por login.');
  console.log('Os registros de verificação foram mantidos apenas no projeto demo local, com e-mails example.test.');
} finally {
  clearTimeout(timeout);
  await Promise.all(accounts.map(app => deleteApp(app)));
}
